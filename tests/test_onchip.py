#!/usr/bin/env python3
"""F91 on-chip peripherals through real port accesses and deterministic qtest time."""
from pathlib import Path
import json
import socket
import tempfile
from ez80_testlib import VM


class Board:
    def __init__(self, root, extra=()):
        self.root = root
        rom = root / 'halt.bin'
        rom.write_bytes(b'\x76')
        path = root / 'qtest.sock'
        self.vm = VM(rom, extra=('-accel', 'qtest', '-nic', 'none',
            '-qtest', f'unix:{path},server=on,wait=off', '-qtest-log', '/dev/null',
            '-rtc', 'base=2024-01-01T00:00:00,clock=vm', *extra))
        self.sock = socket.socket(socket.AF_UNIX)
        self.sock.settimeout(5)
        self.sock.connect(str(path))
        self.stream = self.sock.makefile('rwb', buffering=0)
        self.irq = {}
        children = self.vm.cmd('qom-list', {'path': '/machine/unattached'})
        self.devices = {item['type'][6:-1]: '/machine/unattached/' + item['name']
                        for item in children if item['type'].startswith('child<')}
        self.command('irq_intercept_out ' + self.devices['ez80f91-intc'])
        self.vm.cmd('cont')  # Enable virtual timers; qtest does not execute guest code.

    def command(self, text):
        self.stream.write(text.encode() + b'\n')
        while True:
            result = self.stream.readline().decode().strip().split()
            if result[0] == 'IRQ':
                self.irq[int(result[2])] = result[1] == 'raise'
                continue
            assert result[0] == 'OK', result
            return result[1:]

    def rd(self, port):
        return int(self.command(f'inb {port:#x}')[0], 0)

    def wr(self, port, value):
        self.command(f'outb {port:#x} {value:#x}')

    def step(self, ns):
        self.command(f'clock_step {ns}')

    def inputs(self, port, value):
        self.vm.cmd('qom-set', {'path': self.devices['ez80f91-memory'],
            'property': 'gpio-input-' + port, 'value': value})
        self.rd(0)  # Drain IRQ notifications generated by QMP.

    def vector(self):
        self.rd(0)
        return sum(int(self.irq.get(bit + 1, False)) << bit for bit in range(9))

    def reset(self):
        self.vm.cmd('system_reset')
        self.rd(0)

    def close(self):
        self.stream.close()
        self.sock.close()
        self.vm.close()


with tempfile.TemporaryDirectory(prefix='f91-onchip-') as temp:
    root = Path(temp)
    b = Board(root, ('-device', 'at24c-eeprom,bus=i2c,address=0x50,rom-size=256',
                     '-device', 'i2c-echo,bus=i2c,address=0x42',
                     '-device', 'm25p80,bus=spi'))
    try:
        catalog = json.loads((Path(__file__).parent / 'fixtures/onchip-registers.json').read_text())
        reset_exceptions = {0x50: (0x1f, 0), 0x55: (0, 0)}
        checks = 0
        for item in catalog['registers']:
            b.reset()  # Isolate read side effects (FLASH_DATA increments FLASH_COL).
            port = int(item['address'], 16)
            value = b.rd(port)
            reset = item.get('reset', '')
            if port in reset_exceptions:
                mask, expected = reset_exceptions[port]
            elif len(reset) == 2 and all(c in '0123456789ABCDEF' for c in reset):
                mask, expected = 255, int(reset, 16)
            else:
                continue
            assert value & mask == expected, (item['name'], hex(port), hex(value), hex(expected))
            checks += 1
        assert len(catalog['registers']) == 212
        print(f'PASS: all 212 documented on-chip register addresses read; {checks} defined reset values/masks checked')
        assert [b.rd(i) for i in range(3)] == [8, 0, 1]
        for p in range(4):
            base = 0x96 + p * 4
            assert [b.rd(base + i) for i in (0, 1, 2, 3)] == [255, 255, 0, 0]
        assert b.rd(0x93) == 8
        assert [b.rd(p) for p in range(0xb8, 0xbd)] == [2, 0, 4, 0, 0]
        assert [b.rd(p) for p in range(0xc8, 0xce)] == [0, 0, 0, 0, 0xf8, 0]
        assert [b.rd(p) for p in range(0xd0, 0xd8)] == [0, 0, 1, 0, 0, 0x60, 0, 0]
        print('PASS: product IDs, all four GPIO ports, watchdog, SPI, I2C and UART1 reset registers')

        # All nine GPIO modes, every port; physical pin levels and IRQ vectors.
        for p, name in enumerate('abcd'):
            base, mask = 0x96 + p * 4, 4
            ack = (0xa6, 0xa7, 0xce, 0xcf)[p]
            b.inputs(name, 0xff)
            b.wr(base, 0)
            b.wr(base + 1, 0)
            assert b.rd(base) == 0  # Push-pull output.
            b.wr(base + 2, 0xff)
            assert b.rd(base) == 0  # Open drain, driven low.
            b.wr(base, 0xff)
            assert b.rd(base) == 0xff  # Open drain, released.
            b.inputs(name, 0)
            assert b.rd(base) == 0
            b.wr(base + 1, 0xff)
            assert b.rd(base) == 0xff  # Open source, driven high.
            b.wr(base, 0)
            assert b.rd(base) == 0  # Open source, released.
            b.wr(base + 1, mask)
            b.wr(base + 2, 0)
            b.wr(base + 3, mask)
            b.inputs(name, mask)
            assert not b.irq.get(0, False)  # Alternate function has no GPIO IRQ.
            b.wr(base + 2, mask)  # Falling-edge IRQ.
            b.inputs(name, 0)
            assert b.vector() == 0x80 + p * 32 + 8 and b.irq[0]
            b.wr(ack, mask)
            assert not b.irq[0]
            b.wr(base, mask)  # Rising-edge IRQ.
            b.inputs(name, mask)
            assert b.irq[0]
            b.wr(ack, mask)
            b.wr(base + 1, 0)  # Active high level.
            assert b.irq[0]
            b.wr(ack, mask)
            assert b.irq[0]  # Cannot acknowledge an asserted level.
            b.inputs(name, 0)
            assert not b.irq[0]
            b.wr(base + 2, 0)  # Dual edge.
            b.inputs(name, mask)
            assert b.irq[0]
            b.wr(ack, mask)
            b.inputs(name, 0)
            assert b.irq[0]
            b.wr(ack, mask)
            b.wr(base + 3, 0)
            b.inputs(name, 255)
        print('PASS: GPIO A-D output/open-drain/open-source/mux, both edges, levels and ALT0 acknowledgment')

        b.reset()
        b.wr(0xa1, 3)  # UART1 PC0/PC1 alternate function.
        b.wr(0xd3, 3)
        b.wr(0xd4, 0x10)
        b.wr(0xd1, 1)
        b.wr(0xd0, 0x5a)
        assert b.rd(0xd2) & 15 == 4 and b.vector() == 0x74
        assert b.rd(0xd0) == 0x5a
        b.wr(0xd3, 0x83)
        b.wr(0xd0, 0x34)
        b.wr(0xd1, 0x12)
        assert b.rd(0xd0) == 0x34 and b.rd(0xd1) == 0x12
        b.wr(0xd3, 3)
        b.wr(0xdb, 2)
        b.wr(0xd0, 0x11)
        b.wr(0xdb, 0)
        assert not b.rd(0xd5) & 1
        b.wr(0xbf, 0xff)
        assert b.rd(0xbf) == 0xf7
        b.wr(0xc3, 3)
        b.wr(0xc0, 0xa5)
        assert b.rd(0xc0) == 0xa5
        print('PASS: UART1 DLAB, loopback, RX interrupt vector 074h, power gating and IrDA loopback')

        b.reset()
        # SPI attached to a real QEMU NOR flash; READ JEDEC ID.
        b.wr(0x9d, 0xcc)
        b.wr(0xba, 0xb4)
        def spi(value):
            b.wr(0xbc, value)
            b.step(10000)
            assert b.vector() == 0x7c and b.irq[0]
            status = b.rd(0xbb)
            assert status & 0x80, (hex(status), [hex(b.rd(p)) for p in (0x9a, 0x9b, 0x9c, 0x9d, 0xba)])
            return b.rd(0xbc)
        spi(0x9f)
        assert bytes(spi(0) for _ in range(3)) == bytes.fromhex('202014')
        b.wr(0xb9, 0x10)
        b.wr(0xbc, 0)
        b.wr(0xbc, 1)
        assert b.rd(0xbb) & 0x40
        b.wr(0xdb, 8)
        b.step(10000000)
        assert not b.rd(0xbb) & 0x80
        b.wr(0xdb, 0)
        b.step(10000000)
        assert b.rd(0xbb) & 0x80
        b.inputs('b', 0xfb)
        assert b.rd(0xbb) & 0x10
        print('PASS: real SPI NOR JEDEC ID, vector 07Ch, collision, clock freeze/resume and mode fault')

        for polarity in (0, 1):
            for phase in (0, 1):
                b.reset()
                b.wr(0x9d, 0xcc)
                b.wr(0xba, 0x80 | (polarity << 3) | (phase << 2))
                b.wr(0xba, 0xa0 | (polarity << 3) | (phase << 2))
                b.wr(0xbc, 0xa5)
                pins = (255 & ~12) | (polarity << 3)
                b.inputs('b', pins)
                received = 0
                for i in range(8):
                    pins = (pins & ~0x80) | (((0x3c >> (7 - i)) & 1) << 7)
                    b.inputs('b', pins)
                    b.inputs('b', pins ^ 8)
                    if not phase:
                        received = (received << 1) | bool(b.rd(0x9a) & 0x40)
                    b.inputs('b', pins)
                    if phase:
                        received = (received << 1) | bool(b.rd(0x9a) & 0x40)
                assert received == 0xa5, (polarity, phase, hex(received))
                assert b.rd(0xbc) == 0x3c and b.rd(0xbb) & 0x80
        print('PASS: SPI slave MOSI/MISO exchanges in all four CPOL/CPHA modes')

        b.reset()
        # I2C EEPROM: write address + bytes, STOP, random read/repeated START.
        def i2c_ctl(value, expected):
            b.wr(0xcb, value)
            b.step(100000)
            assert b.rd(0xcc) == expected, (hex(b.rd(0xcc)), hex(expected))
        def i2c_send(value, expected):
            b.wr(0xca, value)
            i2c_ctl(0xc4, expected)
        i2c_ctl(0xe4, 8)
        assert b.vector() == 0x78 and b.irq[0]
        i2c_send(0xa0, 0x18)
        i2c_send(0x20, 0x28)
        i2c_send(0x5a, 0x28)
        i2c_send(0xa5, 0x28)
        i2c_ctl(0xd4, 0xf8)
        i2c_ctl(0xe4, 8)
        i2c_send(0xa0, 0x18)
        i2c_send(0x20, 0x28)
        i2c_ctl(0xe4, 0x10)
        i2c_send(0xa1, 0x40)
        i2c_ctl(0xc4, 0x50)
        assert b.rd(0xca) == 0x5a
        i2c_ctl(0xc0, 0x58)
        assert b.rd(0xca) == 0xa5
        i2c_ctl(0xd0, 0xf8)
        i2c_ctl(0xe4, 8)
        i2c_send(0xaa, 0x20)  # Missing slave must NACK.
        b.wr(0xcd, 1)
        assert b.rd(0xcb) == 0 and b.rd(0xcc) == 0xf8
        print('PASS: real I2C EEPROM write/read, repeated START, ACK/NACK, vector 078h and software reset')

        def wait_status(expected):
            for _ in range(50):
                if b.rd(0xcc) == expected:
                    return
                b.vm.cmd('query-status')
            raise AssertionError((hex(expected), hex(b.rd(0xcc))))
        for ten_bit in (False, True):
            b.reset()
            b.wr(0xc8, 0xf4 if ten_bit else 0xa4)
            b.wr(0xc9, 0x52)
            i2c_ctl(0xe4, 8)
            i2c_send(0x84, 0x18)
            for value in ((0x7a, 0x52, 0x34) if ten_bit else (0x52, 0x12, 0x34)):
                i2c_send(value, 0x28)
            b.wr(0xcb, 0xd4)
            b.step(100000)
            wait_status(0x60)
            received = []
            for _ in range(1 if ten_bit else 2):
                b.wr(0xcb, 0xc4)
                wait_status(0x80)
                received.append(b.rd(0xca))
            assert received == ([0x34] if ten_bit else [0x12, 0x34])
            b.wr(0xcb, 0xc4)
            wait_status(0xa0)
        print('PASS: external asynchronous I2C master addresses the on-chip slave with 7- and 10-bit addresses')

        b.reset()
        for i, base in enumerate((0x60, 0x65, 0x6f, 0x74)):
            b.wr(base + 3, 100)
            b.wr(base + 4, 0)
            b.wr(base + 1, 1)
            b.wr(base, 3)
            b.step(100000)
            assert b.vector() == 0x54 + i * 4 and b.irq[0]
            assert b.rd(base + 2) == 1 and b.rd(base + 2) == 0
            assert not b.rd(base) & 1
        print('PASS: all four timer channels, one-shot countdown, vectors 054h..060h, sticky/read-clear EOC')

        b.reset()
        b.inputs('b', 255)
        b.wr(0x9d, 3)
        b.wr(0x68, 3)
        b.wr(0x69, 0)
        b.wr(0x6a, 15)
        b.wr(0x66, 7)
        b.wr(0x65, 0x47)  # Timer1 event counter, falling EC0, continuous.
        b.inputs('b', 254)
        assert b.rd(0x68) == 2
        assert b.rd(0x6b) == 2 and b.rd(0x6c) == 0
        assert b.rd(0x67) & 2
        b.inputs('b', 255)
        b.inputs('b', 254)
        b.inputs('b', 255)
        b.inputs('b', 254)
        assert b.rd(0x68) == 3 and b.rd(0x67) & 1
        b.wr(0x65, 0)
        b.wr(0x99, 0x40)
        b.wr(0x72, 2)
        b.wr(0x73, 0)
        b.wr(0x6f, 0x63)  # Timer2 event counter, rising EC1, one shot.
        for value in (191, 255, 191, 255):
            b.inputs('a', value)
        assert b.rd(0x71) == 1 and not b.rd(0x6f) & 1
        print('PASS: external event counts on EC0/EC1 and Timer1 input capture values/IRQ')

        b.reset()
        b.inputs('a', 255)
        b.wr(0x99, 15)
        b.wr(0x80, 1)
        b.wr(0x81, 3)
        b.wr(0x82, 70)
        b.wr(0x83, 0)
        b.wr(0x77, 100)
        b.wr(0x78, 0)
        b.wr(0x75, 9)
        b.wr(0x74, 3)
        b.step(2500)
        assert b.rd(0x96) & 1 and b.rd(0x76) == 8
        assert b.vector() == 0  # Compare IRQ was acknowledged above.
        b.step(6000)
        assert b.rd(0x76) == 1
        b.reset()
        b.wr(0x99, 0x11)
        b.wr(0x9d, 0x10)
        b.inputs('b', 255)
        b.wr(0x79, 0xc3)  # PWM0, complement, power trip.
        b.wr(0x7a, 3)     # Three SCLK periods of dead time.
        b.wr(0x7b, 0x4c)  # IC2 trip, PWM low/complement high.
        for port, value in ((0x7c, 70), (0x7d, 0), (0x84, 30), (0x85, 0),
                            (0x77, 100), (0x78, 0), (0x75, 3), (0x74, 7)):
            b.wr(port, value)
        b.step(2500)
        assert b.rd(0x96) & 0x11 == 1
        b.step(3300)
        assert b.rd(0x96) & 0x11 == 0x10
        b.inputs('b', 0xef)
        assert b.rd(0x7b) & 1 and b.rd(0x76) & 2
        assert b.rd(0x96) & 0x11 == 0x10
        b.wr(0x7b, 0x4c)
        assert not b.rd(0x7b) & 1
        print('PASS: Timer3 output compare/toggle, PWM edges, complementary output and latched power trip')

        b.reset()
        b.wr(0xed, 1)
        for offset, value in enumerate((58, 59, 23, 1, 1, 1, 24, 20)):
            b.wr(0xe0 + offset, value)
        b.wr(0xe8, 59)
        b.wr(0xe9, 59)
        b.wr(0xec, 3)
        b.wr(0xed, 0x40)
        b.step(1000000000)
        assert b.vector() == 0x6c and b.irq[0]
        assert b.rd(0xed) == 0xc0 and b.rd(0xed) == 0x40
        assert not b.irq[0]
        b.step(1000000000)
        assert b.rd(0xe0) == 0 and b.rd(0xe3) == 2 and not b.irq[0]
        print('PASS: RTC alarm compares all enabled fields, vector 06Ch, read-clear IRQ and midnight rollover')

        b.reset()
        b.wr(0x93, 0xcb)  # 32 internal-RC clocks, NMI, 3.2ms.
        b.wr(0x93, 0)
        assert b.rd(0x93) == 0xcb
        b.step(2000000)
        b.wr(0x94, 0xa5)
        b.wr(0x94, 0x5a)
        b.step(2000000)
        assert b.rd(0x93) == 0xcb
        b.step(1300000)
        assert b.rd(0x93) == 0xdb
        b.reset()
        b.wr(0x93, 0x83)  # 2^18 SCLK cycles, reset, ~5.24ms.
        b.step(6000000)
        b.vm.cmd('query-status')  # Complete the deferred system-reset request.
        assert b.rd(0x93) == 0x28
        b.reset()
        assert b.rd(0x93) == 8
        print('PASS: watchdog write lock, A5/5A feed, timeout NMI flag, reset and reset-cause retention')

        b.reset()
        b.wr(0x41, 0)
        for tx in (0, 1):
            b.wr(0x20, 0x40 | (tx << 5))
            for i in range(32):
                b.wr(0x57, i)
                b.wr(0x58, i & 3)
            assert b.rd(0x59) & (0x80 if tx else 8)
            for i in range(32):
                assert b.rd(0x57) | (b.rd(0x58) << 8) == i | ((i & 3) << 8)
            assert b.rd(0x59) == 0x33
        b.wr(0x3e, 2)
        b.wr(0x3f, 0)
        b.wr(0x3b, 0x30)
        assert b.rd(0x4e) == 0x22 and b.rd(0x50) & 31 == 0
        b.step(6000)
        assert b.rd(0x4e) == 0xff and b.rd(0x4f) == 0xff
        assert b.rd(0x50) & 31 == 1
        assert b.rd(0x4d) & 0x40
        b.wr(0x3b, 0)
        print('PASS: both EMAC 10-bit test FIFOs, full/empty flags and clocked PHY scan/address increment')

        b.wr(0xb6, 0x80)
        b.wr(0xb7, 0x80)
        assert b.rd(0xb6) == 0x80
        b.step(2000000)
        assert b.rd(0xb6) == b.rd(0xb7) == 0x60
        b.wr(0xb6, 0x7f)
        assert b.rd(0xb6) == 0x60  # Result flags are read-only.
        print('PASS: both MBIST controllers complete real destructive RAM pattern tests')
    finally:
        b.close()

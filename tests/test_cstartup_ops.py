 r.emit(0xed,0x12,0xfd,0xed,0x55,0x04,0xed,0x54,0xff,0x76)
 run(d,'lea-signed-and-cross-index',r,{'DE':0xffe0fd,'IY':0xffe104,
     'IX':0xffe103,'AF':1})

